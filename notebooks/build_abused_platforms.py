"""
Build backend/app/abused_platforms.txt: well-established registered domains
whose SUBDOMAINS are handed out to other people (site builders, web hosts,
CDNs, mailing and link-tracking tools), found from the phishing data rather
than picked by hand.

A domain is listed when it is in the Tranco top 250,000 (reputation.MAX_RANK),
known phishing URLs use 3 or more different subdomains of it, and it is not
already a hosting platform in reputation.py. Its rank describes the platform,
not a customer's subdomain, so ml_state's reputable-site rule never clears
a link on it.

Phishing sources: PhiUSIIL phishing URLs and phish_feed_urls.csv rows first
seen before 2026-01-01, so the 2026 evaluation sets (realworld_eval_set.csv,
outputs/future_test_*.csv) stay unseen.

Run: .venv/Scripts/python notebooks/build_abused_platforms.py
"""
import os
import sys
from urllib.parse import urlparse

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "backend"))
from app.reputation import MAX_RANK, _extract_icann, _load_ranks, is_user_content_host  # noqa: E402

MIN_SUBDOMAINS = 3
CUTOFF = "2026-01-01"
OUT = os.path.join(ROOT, "backend", "app", "abused_platforms.txt")


def host_of(url: str) -> str:
    raw = url.strip()
    if not raw.lower().startswith(("http://", "https://")):
        raw = "http://" + raw
    try:
        return (urlparse(raw).hostname or "").lower()
    except ValueError:
        return ""


def main():
    phi = pd.read_csv(os.path.join(ROOT, "PhiUSIIL_Phishing_URL_Dataset.csv"), usecols=["URL", "label"])
    feed = pd.read_csv(os.path.join(ROOT, "phish_feed_urls.csv"), usecols=["url", "first_seen"])
    urls = pd.concat([phi[phi.label == 0].URL, feed[feed.first_seen < CUTOFF].url]).dropna().astype(str)

    hosts = pd.DataFrame({"host": urls.map(host_of).unique()})
    hosts["domain"] = hosts.host.map(lambda h: _extract_icann(h).top_domain_under_public_suffix or "")
    hosts = hosts[(hosts.domain != "") & (hosts.host != hosts.domain) & (hosts.host != "www." + hosts.domain)]

    ranks = _load_ranks()
    counts = hosts.groupby("domain").host.nunique()
    listed = sorted(
        d for d, n in counts.items()
        if n >= MIN_SUBDOMAINS
        and ranks.get(d, MAX_RANK + 1) <= MAX_RANK
        and not is_user_content_host("https://x." + d)
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(
            "# Generated by notebooks/build_abused_platforms.py - do not edit by hand.\n"
            f"# Tranco top {MAX_RANK:,} domains with phishing on >= {MIN_SUBDOMAINS} different\n"
            f"# subdomains (PhiUSIIL + feed URLs first seen before {CUTOFF}).\n"
        )
        fh.write("\n".join(listed) + "\n")
    print(f"{len(listed)} domains written to {OUT}")


if __name__ == "__main__":
    main()
